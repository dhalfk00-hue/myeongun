def _norm_val(spec, v):
    """최상위 단일값/mount_marks 정리."""
    if spec is bool:
        return bool(v) if isinstance(v, (bool, int)) else str(v).lower() in ("true", "1", "yes", "있음", "예")
    if isinstance(spec, list) and spec and isinstance(spec[0], dict):   # mount_marks
        out = []
        for it in v if isinstance(v, list) else []:
            if isinstance(it, dict) and it.get("mark") in spec[0]["mark"] and it.get("where") in spec[0]["where"]:
                out.append({"mark": it["mark"], "where": it["where"]})
        return out
    return v if v in spec else spec[0]


