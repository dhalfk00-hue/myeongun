def normalize(features: dict) -> dict:
    """AI/검출기 출력의 오타·누락을 스키마 기본값으로 정리."""
    f = features if isinstance(features, dict) else {}
    out = {}
    for key, (spec, _) in SCHEMA.items():
        v = f.get(key)
        if key == "specials":
            out[key] = [x for x in (v or []) if x in spec] if isinstance(v, list) else []
        elif isinstance(spec, dict):
            d = v if isinstance(v, dict) else {}
            sub = {}
            for k, s in spec.items():
                if (key, k) in MULTI or s is MARKS:
                    sub[k] = [x for x in (d.get(k) or []) if x in s] if isinstance(d.get(k), list) else []
                elif s is bool:
                    sub[k] = _norm_val(bool, d.get(k, False))
                else:
                    sub[k] = d.get(k) if d.get(k) in s else s[0]
            out[key] = sub
        else:
            out[key] = _norm_val(spec, v)
    out["valid"] = f.get("valid", True) is not False
    out["retry_tip"] = str(f.get("retry_tip", "") or "")
    out["hand"] = f.get("hand", "오른손")
    out["confidence"] = f.get("confidence", "")
    return out


def schema_json() -> dict:
    """JSON 직렬화 가능한 스키마 (bool → "bool")."""
    def conv(x):
        if x is bool:
            return "bool"
        if isinstance(x, dict):
            return {k: conv(v) for k, v in x.items()}
        if isinstance(x, list):
            return [conv(v) for v in x]
        return x
    return {k: conv(v[0]) for k, v in SCHEMA.items()}


def schema_for_prompt() -> str:
    """프롬프트에 넣을 특징 목록(사람이 읽는 형태)."""
    lines = []
    for key, (spec, desc) in SCHEMA.items():
        if isinstance(spec, dict):
            parts = []
            for k, s in spec.items():
                if s is bool:
                    parts.append(f'"{k}": true|false')
                elif (key, k) in MULTI or s is MARKS:
                    parts.append(f'"{k}": [{"|".join(s)} 중 해당하는 것들]')
                else:
                    parts.append(f'"{k}": {"|".join(s)}')
            lines.append(f'- "{key}" ({desc}): {{ ' + ", ".join(parts) + " }")
        elif key == "mount_marks":
            lines.append(f'- "mount_marks" ({desc}): [{{"mark": {"|".join(spec[0]["mark"])}, "where": {"|".join(spec[0]["where"])}}}]')
        elif key == "specials":
            lines.append(f'- "specials" ({desc}): [{"|".join(spec)} 중 해당하는 것들]')
        else:
            lines.append(f'- "{key}" ({desc}): {"|".join(spec)}')
    lines.append("- 구 이름: " + ", ".join(f"{k}={v}" for k, v in MOUNTS.items()))
    return "\n".join(lines)


