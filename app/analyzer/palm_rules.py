def josa(word, pair="이가"):
    """받침 유무에 따라 조사 선택 (이/가, 은/는, 과/와)."""
    ch = word.rstrip(")'\" ")[-1:] or "가"
    code = ord(ch) - 0xAC00
    has = 0 <= code < 11172 and code % 28 != 0
    return pair[0] if has else pair[1]


