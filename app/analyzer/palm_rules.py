def interpret(features: dict, saju_groups: dict | None = None) -> dict:
    f = normalize(deepcopy(features))
    if not f["valid"]:
        return {"valid": False, "retry_tip": f["retry_tip"] or "손바닥 전체가 밝고 선명하게 나오도록 다시 찍어 주세요.",
                "disclaimer": DISCLAIMER}
    acc = Acc()
    _life(acc, f["life"])
    if f["simian"] in ("없음",):
        _head(acc, f["head"])
        _heart(acc, f["heart"])
    else:
        _simian(acc, f["simian"])
    _fate(acc, f["fate"])
    _sun(acc, f["sun"], f["fate"]["presence"])
    _business(acc, f["business"])
    _marriage(acc, f["marriage"])
    _shape_fingers_mounts(acc, f)
    _specials(acc, f)

    order = ["생명선", "두뇌선", "감정선", "막쥔손금", "운명선", "태양선(재물선)", "사업선", "결혼선"]
    lines = []
    for nm in order:
        if nm in acc.lines:
            L = acc.lines[nm]
            if not L["meaning"] and not L["observed"]:
                continue
            lines.append({"name": nm, "observed": " · ".join(L["observed"]) or "확인 어려움",
                          "meaning": " ".join(L["meaning"]) or "뚜렷한 특징은 보이지 않아요.",
                          "score": max(1, min(5, round(L["score"])))})

    # 전통 원칙: 3대선 먼저 → 운명선
    base3 = [l["score"] for l in lines if l["name"] in ("생명선", "두뇌선", "감정선", "막쥔손금")]
    fate = next((l["score"] for l in lines if l["name"] == "운명선"), None)
    if base3 and fate is not None and fate >= 4 and sum(base3) / len(base3) < 3:
        acc.add("일·사업", "운명선은 좋지만, 전통 원칙대로 3대선(몸·머리·마음)을 먼저 다져야 운이 제대로 열려요.", 221755044525)
    if base3 and fate is not None and fate <= 2 and sum(base3) / len(base3) >= 3.5:
        acc.add("일·사업", "운명선이 약해도 3대선이 튼튼해서, 내 페이스대로 안정적으로 잘 풀리는 손이에요.", 221755044525)

    hl = list(dict.fromkeys(acc.highlights))
    best = sorted(lines, key=lambda l: -l["score"])[:2]
    if hl:
        w = ", ".join(hl[:3])
        summary = f"{w}{josa(w)} 돋보이는 손이에요." + (f" 선 중에서는 {best[0]['name']}{josa(best[0]['name'])} 가장 좋아요." if best else "")
    elif best:
        w = best[0]["name"] + (f"{josa(best[0]['name'], '과와')} {best[1]['name']}" if len(best) > 1 else "")
        summary = f"{w}{josa(w)} 돋보이는 손이에요."
    else:
        summary = "고른 특징이 아직 많지 않아요. 손금 단계에서 몇 가지만 더 골라 주시면 풀이가 풍성해져요."

    sections = {k: _pick(v) for k, v in acc.sec.items() if v}
    if saju_groups:
        cross = saju_cross(f, saju_groups)
        if cross:
            sections["사주×손금"] = " ".join(cross) + " (수상학에서는 엄지=비겁, 검지=관성, 중지=인성, 약지=식상, 소지=재성으로 봐요.)"
            acc._s((221562605119,))
    tips = [t for t in acc.tips if t]
    advice = " ".join(tips[:3]) if tips else "좋은 선은 자랑보다 꾸준함으로 지킬 때 더 진해진다고 봐요. 지금 하는 일을 한 걸음씩 이어 가세요."
    return {"valid": True, "retry_tip": "", "hand": f["hand"], "summary": summary, "lines": lines,
            "extras": acc.extras, "sections": sections, "advice": advice,
            "framework": "전통 수상학(손금 초·중·고급 강의) 기반 규칙 해석",
            "sources": acc.src[:40], "features": f, "disclaimer": DISCLAIMER}
