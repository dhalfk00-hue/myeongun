class Acc:
    """섹션별 문장·근거·점수를 모은다."""
    SECTIONS = ["성격", "재물", "일·사업", "연애·관계", "건강·생활"]

    def __init__(self):
        self.lines = {}
        self.sec = {s: [] for s in self.SECTIONS}
        self.extras, self.src, self.tips, self.highlights = [], [], [], []

    def add(self, sec, text, *src):
        if text and text not in self.sec[sec]:
            self.sec[sec].append(text)
        self._s(src)

    def line(self, name, observed, text, delta=0, *src):
        L = self.lines.setdefault(name, {"name": name, "observed": [], "meaning": [], "score": 3.0})
        if observed and observed not in L["observed"]:
            L["observed"].append(observed)
        if text and text not in L["meaning"]:
            L["meaning"].append(text)
        L["score"] += delta
        self._s(src)

    def extra(self, text, *src):
        if text not in self.extras:
            self.extras.append(text)
        self._s(src)

    def tip(self, text):
        if text not in self.tips:
            self.tips.append(text)

    def _s(self, src):
        for s in src:
            u = SRC.format(s)
            if u not in self.src:
                self.src.append(u)


