def resolve(name):
    """이름 → (saju.py 에 넘길 place 문자열, 화면 표시용 라벨). 모르는 이름이면 KeyError."""
    name = (name or "서울").strip()
    if name in LON:
        return f"{LON[name]:.2f}", name
    try:
        lon = float(name)
        if 120 <= lon <= 135:
            return f"{lon:.2f}", f"경도 {lon:.2f}°"
    except ValueError:
        pass
    raise KeyError(name)
