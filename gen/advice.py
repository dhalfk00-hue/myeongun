def _pick(lst, key, gender=None):
    if gender:
        mine = "(여성은)" if gender == "F" else "(남성은)"
        other = "(남성은)" if gender == "F" else "(여성은)"
        lst = [x.replace(mine + " ", "") for x in lst if not x.startswith(other)]
    if not lst: return ""
    h = sum(ord(ch) * (i + 1) for i, ch in enumerate(key))
    return lst[h % len(lst)]


