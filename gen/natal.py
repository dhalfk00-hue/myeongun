GM = {"비겁": "내 편·경쟁", "식상": "재능·표현", "재성": "돈·현실", "관성": "책임·평판", "인성": "배움·도움"}


def daeun_flow(g1, g2, theme_first):
    if g1 == g2: return theme_first
    return f"{GM[g1]}이 겉에 드러나고, {theme_first}"


def sinsal_text(nm, lst, desc):
    """신살 설명: 첫 문장(별의 뜻) + '자리' 절을 붙인 둘째 문장"""
    ps = [p for p, _ in lst if p in SIN_POS]
    if not ps or ". " not in desc:
        return desc + ((" " + sinsal_pos_line(nm, lst)) if ps else "")
    first, rest = desc.split(". ", 1)
    where = "·".join(dict.fromkeys(SIN_POS[p] for p in ps))
    pn = "·".join(dict.fromkeys(POS_NAME[p] for p in ps))
    return f"{first}. {josa(nm, '이')} {pn}에 있어 {where} 쪽에서 먼저 드러나고, {rest}"
