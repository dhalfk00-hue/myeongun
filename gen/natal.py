REL_POS = {"월": "일과 가정", "년": "집안과 부부", "시": "자녀·미래 계획과 부부"}


def palace_rel_line(c):
    import saju as S
    out = []
    for pos in ("월", "시", "년"):
        if pos not in c.P or (pos == "시" and not c.time_known): continue
        b = c.P[pos]["gz"][1]
        rel = S.pair_relations(c.db, b)
        if "충" in rel:
            return f"원국에서 배우자궁({c.db})이 {POS_NAME[pos]}({b})와 충해, {REL_POS[pos]} 사이에서 균형을 잡는 것이 관계의 과제예요."
        if "육합" in rel or "합" in rel:
            out.append(f"원국에서 배우자궁({c.db})이 {POS_NAME[pos]}({b})와 합해, {REL_POS[pos]}이 서로 끌어 주는 구조예요.")
        elif "형" in rel:
            out.append(f"원국에서 배우자궁({c.db})이 {POS_NAME[pos]}({b})와 형이 걸려, 가까운 사이일수록 말을 고르는 게 좋아요.")
    return out[0] if out else ""


