    if not ps: return ""
    where = "·".join(dict.fromkeys(SIN_POS[p] for p in ps))
    return f"{'·'.join(dict.fromkeys(POS_NAME[p] for p in ps))}에 있어 {where} 쪽에서 먼저 드러나요."


