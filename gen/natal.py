def health_pair_line(c, hi, lo):
    if hi == lo: return ""
    if CTL[hi] == lo:
        mid = GEN[hi]
        return (f"강한 {josa(elw(hi), '이')} 약한 {josa(elw(lo), '을')} 누르는 구조(상극)라 {ORGAN[lo]} 쪽이 먼저 지치기 쉬워요. "
                f"둘 사이를 이어 주는 {elw(mid)} 기운({FILL[mid]})을 채우면 균형이 잡혀요.")
    if GEN[hi] == lo:
        return f"강한 {josa(elw(hi), '이')} 약한 {josa(elw(lo), '을')} 낳아 주는 구조(상생)라 회복력은 있는 편이에요. 다만 {ORGAN[hi]} 쪽 과로가 {ORGAN[lo]}까지 번지지 않게 하세요."
